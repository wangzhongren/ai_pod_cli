#!/usr/bin/env python3
"""Independent acceptance checks for the actual Pod-generated Breakout project.

This is an external evaluator, not a test generated by Pod. It executes untouched
project files in a disposable copy through their registered PipelineRunner routes.
Physics fixtures use the generated simulator's top-left positions, launch command,
and uppercase states. Nothing in the application is patched or mocked.
"""

from __future__ import annotations

import argparse
import copy
import hashlib
import io
import json
import os
import shutil
import sys
import tempfile
import traceback
from contextlib import redirect_stderr, redirect_stdout
from datetime import datetime, timezone
from pathlib import Path
from time import perf_counter


sys.dont_write_bytecode = True
sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from ai_pod_cli.config_store import ConfigStore
from ai_pod_cli.runner import PipelineRunner


STEP_ROUTE = "step_breakout_simulation"
HEADLESS_ROUTE = "run_headless_breakout"


def plain(value):
    if hasattr(value, "model_dump"):
        return plain(value.model_dump())
    if isinstance(value, dict):
        return {str(key): plain(item) for key, item in value.items()}
    if isinstance(value, (list, tuple)):
        return [plain(item) for item in value]
    return value


def entity(state, kind):
    return next(item for item in state["entities"] if item["kind"] == kind)


def view(state):
    result = {key: plain(state.get(key)) for key in (
        "game_state", "score", "lives", "frame_count", "simulation_time",
        "ball_attached", "last_frame_events", "previous_commands",
    )}
    if state.get("entities"):
        ball = entity(plain(state), "ball")
        result["ball_position"] = ball["position"]
        result["ball_velocity"] = ball["velocity"]
        result["remaining_bricks"] = sum(
            item["kind"] == "brick" and item["enabled"]
            for item in plain(state)["entities"]
        )
    return result


def require(condition, message):
    if not condition:
        raise AssertionError(message)


def scene_signature(state):
    return sorted(
        (item["id"], item["kind"], item["enabled"],
         item["position"]["x"], item["position"]["y"],
         item["velocity"]["x"], item["velocity"]["y"])
        for item in state["entities"]
    )


def evaluate(project, results_dir):
    runner = PipelineRunner()
    config = ConfigStore()
    dt = float(config.get("game.fixed_timestep", 1 / 60))
    results = []

    def step(state=None, commands=None):
        params = copy.deepcopy(state or {})
        params["commands"] = dict(commands or {})
        params["dt"] = dt
        result, ctx = runner.run_with_context(STEP_ROUTE, params)
        require(not isinstance(result, dict) or result.get("status") != "failure",
                f"Step route reported failure: {result}")
        return plain({**ctx.params, **ctx.data})

    def ready():
        state = step()
        require(state["game_state"] == "READY", "Fresh scene is not READY")
        return state

    def playing():
        state = ready()
        state.update(game_state="PLAYING", ball_attached=False)
        ball = entity(state, "ball")
        ball["position"] = {"x": 400.0, "y": 400.0}
        ball["velocity"] = {"x": 120.0, "y": -60.0}
        return state

    def test(name, check):
        started = perf_counter()
        detail = {}
        captured = io.StringIO()
        with redirect_stdout(captured), redirect_stderr(captured):
            try:
                check(detail)
                record = {"name": name, "status": "passed", "evidence": detail}
            except Exception as error:
                ctx = getattr(error, "aipod_context", None)
                if ctx is not None:
                    detail["partial_state"] = view(plain({**ctx.params, **ctx.data}))
                record = {
                    "name": name, "status": "failed", "evidence": detail,
                    "error": {"type": type(error).__name__, "message": str(error)},
                    "traceback": traceback.format_exc(),
                }
        record["duration_seconds"] = round(perf_counter() - started, 4)
        if captured.getvalue():
            record["application_log"] = captured.getvalue()
        results.append(record)

    def headless(detail):
        artifacts = Path(tempfile.mkdtemp(prefix="headless-", dir=results_dir))
        screenshot = artifacts / "headless-120.png"
        summary = artifacts / "headless-120.json"
        simulation_file = (project / "modules/services/breakoutsimulationservice.py").resolve()
        observed = []
        calls = 0

        def profile(frame, event, _arg):
            nonlocal calls
            if frame.f_code.co_name != "execute" or os.path.realpath(frame.f_code.co_filename) != str(simulation_file):
                return
            if event == "call":
                calls += 1
            elif event == "return" and "ctx" in frame.f_locals:
                ctx = frame.f_locals["ctx"]
                try:
                    observed.append(view(plain({**ctx.params, **ctx.data})))
                except Exception as error:
                    observed.append({"observation_error": str(error)})

        error = None
        ctx = None
        old_profile = sys.getprofile()
        sys.setprofile(profile)
        try:
            _result, ctx = runner.run_with_context(HEADLESS_ROUTE, {
                "max_frames": 120,
                "screenshot_path": str(screenshot), "summary_path": str(summary),
            })
        except Exception as caught:
            error = caught
            ctx = getattr(caught, "aipod_context", None)
        finally:
            sys.setprofile(old_profile)
        detail.update(
            artifacts={"screenshot": str(screenshot), "summary": str(summary)},
            actual_simulation_calls=calls,
            first_frame=observed[0] if observed else None,
            final_simulation_frame=observed[-1] if observed else None,
            distinct_ball_positions=len({
                json.dumps(item.get("ball_position"), sort_keys=True) for item in observed
            }),
            screenshot_exists=screenshot.is_file(), summary_exists=summary.is_file(),
        )
        if ctx is not None:
            detail["final_state"] = view(plain({**ctx.params, **ctx.data}))
        if error is not None:
            detail["runtime_error"] = f"{type(error).__name__}: {error}"
        checks = {
            "route_completed": error is None,
            "executed_120_physics_steps": calls == 120,
            "ball_really_moved": detail["distinct_ball_positions"] > 1,
            "reported_frame_count_matches_calls": ctx is not None and ctx.get("frame_count") == calls,
            "png_written": screenshot.is_file() and screenshot.read_bytes().startswith(b"\x89PNG\r\n\x1a\n"),
            "summary_written": summary.is_file(),
        }
        if summary.is_file():
            payload = json.loads(summary.read_text(encoding="utf-8"))
            detail["summary_payload"] = payload
            checks["summary_frame_count_matches_calls"] = payload.get("frame_count") == calls
        detail["checks"] = checks
        require(all(checks.values()), "Headless acceptance failed: " + ", ".join(
            name for name, passed in checks.items() if not passed
        ))

    def launch(detail):
        before = ready()
        after = step(before, {"launch": True})
        detail.update(before=view(before), after=view(after))
        require(after["game_state"] == "PLAYING" and not after["ball_attached"],
                "Launch did not enter PLAYING with a released ball")
        require(entity(after, "ball")["position"] != entity(before, "ball")["position"],
                "Ball did not move after launch")
        require(after["simulation_time"] > before["simulation_time"], "Physics time did not advance")

    def wall(detail):
        before = playing()
        ball = entity(before, "ball")
        ball["position"] = {"x": 0.5, "y": 400.0}
        ball["velocity"] = {"x": -180.0, "y": 0.0}
        detail["before"] = view(before)
        after = step(before)
        detail["after"] = view(after)
        require(entity(after, "ball")["velocity"]["x"] > 0, "Left-wall impact did not reverse x velocity")
        require(entity(after, "ball")["position"]["x"] >= 0, "Ball remained outside the left wall")

    def paddle(detail):
        before = playing()
        ball, pad = entity(before, "ball"), entity(before, "paddle")
        ball["position"] = {
            "x": pad["position"]["x"] + (pad["size"]["x"] - ball["size"]["x"]) / 2,
            "y": pad["position"]["y"] - ball["size"]["y"] - 0.5,
        }
        ball["velocity"] = {"x": 0.0, "y": 180.0}
        detail["before"] = view(before)
        after = step(before)
        detail["after"] = view(after)
        require(entity(after, "ball")["velocity"]["y"] < 0, "Paddle impact did not bounce the ball upward")
        require(after["lives"] == before["lives"], "Paddle bounce incorrectly lost a life")

    def brick(detail):
        before = playing()
        ball = entity(before, "ball")
        target = max((item for item in before["entities"] if item["kind"] == "brick"),
                     key=lambda item: item["position"]["y"])
        ball["position"] = {
            "x": target["position"]["x"] + (target["size"]["x"] - ball["size"]["x"]) / 2,
            "y": target["position"]["y"] + target["size"]["y"] + 0.5,
        }
        ball["velocity"] = {"x": 0.0, "y": -180.0}
        detail.update(before=view(before), target_brick=copy.deepcopy(target))
        after = step(before)
        detail["after"] = view(after)
        hit = next(item for item in after["entities"] if item["id"] == target["id"])
        require(not hit["enabled"], "Collided brick was not disabled")
        require(after["score"] == before["score"] + int(config.get("game.points_per_brick", 10)),
                "Brick collision did not award the configured score")
        require(entity(after, "ball")["velocity"]["y"] > 0, "Brick impact did not reverse vertical velocity")

    def pause(detail):
        before = playing()
        after = step(before, {"pause": True})
        still = step(after, {})
        detail.update(before=view(before), paused=view(after), next_frame=view(still))
        require(after["game_state"] == still["game_state"] == "PAUSED", "Pause did not persist after key release")
        require(scene_signature(before) == scene_signature(after) == scene_signature(still),
                "Physics positions or velocities changed while paused")
        require(still["simulation_time"] == before["simulation_time"], "Physics time advanced while paused")

    def held_pause(detail):
        before = playing()
        paused = step(before, {"pause": True})
        held = step(paused, {"pause": True})
        detail.update(paused=view(paused), held_next_frame=view(held))
        require(held["game_state"] == "PAUSED", "Holding pause for two frames toggled the state twice")
        require(scene_signature(paused) == scene_signature(held), "Holding pause resumed physics")

    def reset(detail):
        baseline = ready()
        changed = playing()
        changed.update(score=70, lives=1, simulation_time=9.0)
        next(item for item in changed["entities"] if item["kind"] == "brick")["enabled"] = False
        after = step(changed, {"reset": True})
        detail.update(initial=view(baseline), changed=view(changed), reset=view(after))
        require(scene_signature(after) == scene_signature(baseline), "Reset did not restore initial scene geometry and enabled bricks")
        for key in ("score", "lives", "game_state", "simulation_time", "ball_attached"):
            require(after[key] == baseline[key], f"Reset did not restore {key}")

    test("default_headless_120_frames_and_outputs", headless)
    test("single_step_launch", launch)
    test("left_wall_reflection", wall)
    test("paddle_reflection", paddle)
    test("brick_collision_and_score", brick)
    test("pause_keeps_physics_unchanged", pause)
    test("held_pause_is_one_key_edge", held_pause)
    test("reset_restores_initial_scene", reset)
    return {
        "registered_routes": runner.route_names(), "checks": results,
        "passed": sum(item["status"] == "passed" for item in results),
        "failed": sum(item["status"] == "failed" for item in results),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("project", type=Path)
    parser.add_argument("--results-dir", type=Path, default=Path(__file__).resolve().parent / "results/independent-acceptance")
    args = parser.parse_args()
    source = args.project.resolve(strict=True)
    results_dir = args.results_dir.resolve()
    results_dir.mkdir(parents=True, exist_ok=True)
    os.environ.setdefault("SDL_VIDEODRIVER", "dummy")
    os.environ.setdefault("SDL_AUDIODRIVER", "dummy")
    os.environ.setdefault("PYGAME_HIDE_SUPPORT_PROMPT", "1")
    report = {
        "evaluator": "Independent evaluator; not Pod-generated application tests",
        "source_project": str(source),
        "started_at": datetime.now(timezone.utc).isoformat(),
        "execution": "Unmodified disposable copy, registered PipelineRunner routes, no mocks or model calls",
    }
    previous = Path.cwd()
    try:
        with tempfile.TemporaryDirectory(prefix="aipod-independent-engine-") as tmp:
            snapshot = Path(tmp) / "project"
            shutil.copytree(source, snapshot, ignore=shutil.ignore_patterns("__pycache__", ".git", ".aipod", "out"))
            paths = [snapshot / name for name in ("beans_config.json", "routes.toml", "config.toml")]
            for folder in ("modules", "pipelines"):
                paths.extend(sorted((snapshot / folder).rglob("*.py")))
            report["source_sha256"] = {
                str(path.relative_to(snapshot)): hashlib.sha256(path.read_bytes()).hexdigest()
                for path in paths if path.is_file()
            }
            os.chdir(snapshot)
            sys.path.insert(0, str(snapshot))
            report.update(evaluate(snapshot, results_dir))
    except Exception as error:
        report.update(passed=0, failed=1, setup_error={"type": type(error).__name__, "message": str(error)}, traceback=traceback.format_exc())
    finally:
        os.chdir(previous)
    report["status"] = "passed" if report["failed"] == 0 else "failed"
    report["finished_at"] = datetime.now(timezone.utc).isoformat()
    text = json.dumps(report, ensure_ascii=False, indent=2)
    (results_dir / "report.json").write_text(text + "\n", encoding="utf-8")
    print(text)
    return 0 if report["status"] == "passed" else 1


if __name__ == "__main__":
    raise SystemExit(main())
