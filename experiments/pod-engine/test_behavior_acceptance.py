"""Independent acceptance fixtures for the unchanged, Pod-generated engine.

Executed by ai_pod_cli.behavior_tests in a disposable engine copy, not as part
of the framework unit suite. This file was not generated by Pod.
"""

import copy
import json
import tempfile
import sys
import unittest
from pathlib import Path

from ai_pod_cli.runner import PipelineRunner


def plain(value):
    if hasattr(value, "model_dump"):
        return plain(value.model_dump())
    if isinstance(value, dict):
        return {key: plain(item) for key, item in value.items()}
    if isinstance(value, (list, tuple)):
        return [plain(item) for item in value]
    return value


def entity(state, kind):
    return next(item for item in state["entities"] if item["kind"] == kind)


class EngineBehavior(unittest.TestCase):
    def step(self, state=None, commands=None):
        params = copy.deepcopy(state or {})
        params.update(commands=dict(commands or {}), dt=1 / 60)
        _, ctx = PipelineRunner().run_with_context("step_breakout_simulation", params)
        return plain({**ctx.params, **ctx.data})

    def playing(self):
        state = self.step()
        state.update(game_state="PLAYING", ball_attached=False)
        ball = entity(state, "ball")
        ball.update(position={"x": 400.0, "y": 400.0}, velocity={"x": 120.0, "y": -60.0})
        return state

    def test_default_headless(self):
        with tempfile.TemporaryDirectory() as tmp:
            screenshot, summary = Path(tmp) / "frame.png", Path(tmp) / "summary.json"
            simulation = (Path.cwd() / "modules/services/breakoutsimulationservice.py").resolve()
            actual_calls = 0
            def observe(frame, event, _arg):
                nonlocal actual_calls
                if event == "call" and frame.f_code.co_name == "execute" and Path(frame.f_code.co_filename).resolve() == simulation:
                    actual_calls += 1
            error, ctx = None, None
            previous = sys.getprofile()
            sys.setprofile(observe)
            try:
                _, ctx = PipelineRunner().run_with_context("run_headless_breakout", {
                    "max_frames": 120, "seed": 7, "screenshot_path": str(screenshot),
                    "summary_path": str(summary),
                })
            except Exception as caught:
                error = caught
            finally:
                sys.setprofile(previous)
            self.assertEqual(actual_calls, 120, f"Reported frames must match real simulation calls; route error: {error}")
            self.assertIsNone(error, str(error))
            self.assertEqual(ctx.get("frame_count"), 120)
            self.assertGreater(ctx.get("simulation_time"), 0)
            self.assertFalse(ctx.get("ball_attached"))
            self.assertTrue(screenshot.is_file())
            self.assertIsInstance(json.loads(summary.read_text()), dict)

    def test_launch(self):
        before = self.step()
        after = self.step(before, {"launch": True})
        self.assertEqual(after["game_state"], "PLAYING")
        self.assertNotEqual(entity(before, "ball")["position"], entity(after, "ball")["position"])

    def test_wall(self):
        before = self.playing()
        entity(before, "ball").update(position={"x": 0.5, "y": 400.0}, velocity={"x": -180.0, "y": 0.0})
        after = self.step(before)
        self.assertGreater(entity(after, "ball")["velocity"]["x"], 0)
        self.assertIn("wall_left", after["last_frame_events"])

    def test_paddle(self):
        before = self.playing()
        paddle, ball = entity(before, "paddle"), entity(before, "ball")
        ball.update(position={"x": paddle["position"]["x"] + (paddle["size"]["x"] - ball["size"]["x"]) / 2,
                              "y": paddle["position"]["y"] - ball["size"]["y"] - 0.5},
                    velocity={"x": 0.0, "y": 180.0})
        after = self.step(before)
        self.assertLess(entity(after, "ball")["velocity"]["y"], 0)
        self.assertIn("paddle_hit", after["last_frame_events"])

    def test_brick(self):
        before = self.playing()
        brick = max((item for item in before["entities"] if item["kind"] == "brick"),
                    key=lambda item: item["position"]["y"])
        ball = entity(before, "ball")
        ball.update(position={"x": brick["position"]["x"] + (brick["size"]["x"] - ball["size"]["x"]) / 2,
                              "y": brick["position"]["y"] + brick["size"]["y"] + 0.5},
                    velocity={"x": 0.0, "y": -180.0})
        after = self.step(before)
        self.assertGreater(after["score"], before["score"])
        self.assertFalse(next(item for item in after["entities"] if item["id"] == brick["id"])["enabled"])

    def test_pause(self):
        before = self.playing()
        paused = self.step(before, {"pause": True})
        after = self.step(paused)
        self.assertEqual(after["game_state"], "PAUSED")
        self.assertEqual(entity(before, "ball")["position"], entity(after, "ball")["position"])
        self.assertEqual(after["simulation_time"], before["simulation_time"])

    def test_held_pause(self):
        before = self.playing()
        paused = self.step(before, {"pause": True})
        after = self.step(paused, {"pause": True})
        self.assertEqual(after["game_state"], "PAUSED")
        self.assertEqual(entity(paused, "ball")["position"], entity(after, "ball")["position"])

    def test_reset(self):
        initial = self.step()
        before = self.playing()
        before.update(score=70, lives=1)
        entity(before, "brick")["enabled"] = False
        after = self.step(before, {"reset": True})
        self.assertEqual(after["game_state"], "READY")
        self.assertEqual(after["score"], initial["score"])
        self.assertEqual(after["lives"], initial["lives"])
        self.assertEqual(after["entities"], initial["entities"])
